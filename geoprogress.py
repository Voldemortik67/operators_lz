b, q, n = map(int,input("Введите 3 значения 1. Первый элемент прогрессии 2. Множитель прогрессии 3. Номер последнего элемента: ").split())
if (b>=-10000  and b<=10000 and q>=1 and q<=50 and n>=2 and n<=100):
    s = (b*(q ** n - 1))/(q-1)
    print("Сумма геометрической прогрессии равна: ", s)
else:
    print("Некоректо введены числа")